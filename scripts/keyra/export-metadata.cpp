#include "controls.h"
#include <iostream>
#include <iomanip>
#include <limits>

int main() {
    const keyra::Parameters initial;
    std::cout << "// Generated by scripts/keyra/build-dsp.sh.\n"
              << "// Required Notice: Copyright (c) 2026 Protocodus (https://protocodus.cz)\n"
              << "export const controls = [\n";
    for (const auto& c : web::controls) {
        const char* kind = c.type == web::ControlType::body ? "choice" :
            c.type == web::ControlType::polarity ? "toggle" : "range";
        std::cout << "  {id:" << std::quoted(c.id) << ",name:" << std::quoted(c.name)
                  << ",min:" << c.minimum << ",max:" << c.maximum << ",initial:" << web::read(c, initial)
                  << ",kind:" << std::quoted(kind) << "},\n";
    }
    std::cout << "];\nexport const bodies = [\n";
    for (const auto body : keyra::bodyOrder) {
        const int value = static_cast<int>(body);
        std::cout << "  {name:" << std::quoted(keyra::bodyNames[value]) << ",value:" << value << "},\n";
    }
    std::cout << "];\nexport const micNames = [";
    for (auto name : keyra::micNames) std::cout << std::quoted(name) << ",";
    std::cout << "];\nexport const presets = [\n";
    for (const auto& preset : keyra::factoryPresets) {
        const auto p = keyra::withPreset(initial, preset);
        std::cout << "  {name:" << std::quoted(preset.name) << ",values:{";
        for (const auto& c : web::controls)
            if (c.inPreset) std::cout << c.id << ":" << web::read(c, p) << ",";
        std::cout << "}},\n";
    }
    std::cout << "];\n";
}
