"""Make Binaryen 120's generated JavaScript an isolated synchronous factory."""
from pathlib import Path
import sys

source, destination = map(Path, sys.argv[1:])
module = source.read_text()
footer = "\nvar retasmFunc = asmFunc({"
wasi = "import * as wasi_snapshot_preview1 from 'wasi_snapshot_preview1';"
if module.count(footer) != 1:
    raise SystemExit("Unexpected wasm2js output: use Binaryen 120.")
body = module.split(footer)[0].removeprefix(wasi).lstrip()
if body.startswith("import "):
    raise SystemExit("Review new runtime imports before publishing this build.")
header = """// Generated by scripts/keyra/build-dsp.sh. See LICENSE and THIRD_PARTY_NOTICES.md.
// Required Notice: Copyright (c) 2026 Protocodus (https://protocodus.cz)
import { runtimeImports } from './runtime.mjs';

export function createCore() {
"""
text = header + body + "\n  return asmFunc(runtimeImports);\n}\n"
destination.write_text("\n".join(line.rstrip() for line in text.splitlines()) + "\n")
