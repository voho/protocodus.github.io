#!/usr/bin/env bash
# Generate the shipped JavaScript from the same C++17 sources as the instrument.
set -euo pipefail

site=$(cd "$(dirname "$0")/../.." && pwd)
source_checkout=${1:?Pass the path to the virtual-instrument-oregana checkout}
read -r revision < "$site/scripts/oregana/revision.txt"
build=$(mktemp -d)
trap 'rm -rf "$build"' EXIT

# Read the pinned tree so that local changes in the instrument checkout cannot
# silently change the published build.
git -C "$source_checkout" archive "$revision" Source/DSP LICENSE THIRD_PARTY_NOTICES.md | tar -xC "$build"
"${WASI_CXX:-clang++-19}" --target=wasm32-wasi --sysroot="${WASI_SYSROOT:-/usr}" \
    -mexec-model=reactor -std=c++17 -O2 -ffp-contract=off -fno-exceptions -fno-rtti \
    -fno-unroll-loops -fno-vectorize -fno-slp-vectorize -include "$site/scripts/oregana/scalar.h" \
    -Wl,--initial-memory=67108864 -Wl,--max-memory=67108864 -I"$build/Source/DSP" \
    "$build/Source/DSP/OreganaEngine.cpp" "$site/scripts/oregana/bridge.cpp" -o "$build/organ.wasm"
wasm2js "$build/organ.wasm" -O2 -o "$build/module.js"
python3 "$site/scripts/oregana/package-dsp.py" "$build/module.js" "$site/fun/oregana/dsp/core.mjs"
cp "$build/LICENSE" "$site/fun/oregana/dsp/"
{
    cat "$build/THIRD_PARTY_NOTICES.md"
    cat <<'NOTICE'

## Browser runtime

The JavaScript build also includes routines from WASI libc, musl and LLVM,
and code generated by Binaryen. [Runtime licenses](./RUNTIME-LICENSES.txt)
NOTICE
} > "$site/fun/oregana/dsp/THIRD_PARTY_NOTICES.md"
"${CXX:-c++}" -std=c++17 -I"$build/Source/DSP" "$site/scripts/oregana/export-metadata.cpp" -o "$build/export-metadata"
"$build/export-metadata" > "$site/fun/oregana/metadata.js"
