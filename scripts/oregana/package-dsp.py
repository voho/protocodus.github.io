"""Package Binaryen 120's ES-module output as an isolated, synchronous processor."""

from hashlib import sha256
from pathlib import Path
import re
import sys

# A stock JS engine widens nearly every single-precision operation in these two
# per-pipe loops. asm.js lets engines recognize the original float operations.
# The module is ordinary, correct JS on browsers without asm.js acceleration.
# Match the audited generated bodies independently of Binaryen’s function numbers.
PIPE_KERNELS = {
    "986111d4d585b9cf34235ea7eab957578916f6ab3478aaac6701a390ee6a44d9": "renderFlue",
    "2a0787161a8b135ba78cbcfd6a51a8569ea1f6dc96b92fe71847c97b6dbfe4d4": "renderReed",
}


def extract_pipe_kernels(body):
    definitions = {}
    bindings = []

    def extract(match):
        original, signature_body = match.groups()
        name = PIPE_KERNELS.get(sha256(signature_body.encode()).hexdigest())
        if name is None:
            return match[0]
        signature, code = signature_body.split("\n", 1)
        arguments = signature[1:signature.index(")")].split(", ")
        # All arguments are i32 pointers or frame counts. Coerce typed-array
        # reads as asm.js requires. Stores already round to the heap's type.
        annotations = "".join(f"  {arg} = {arg}|0;\n" for arg in arguments)
        code = re.sub(r"HEAP32\[[^\[\]]+\](?!\s*=)", r"(\g<0>|0)", code)
        code = re.sub(r"HEAPF32\[[^\[\]]+\](?!\s*=)", r"Math_fround(\g<0>)", code)
        definitions[name] = f" function {name}{signature}\n{annotations}{code}"
        bindings.append(f" const {original} = kernels.{name};")
        return ""

    body = re.sub(r"^ function (\$\d+)(\(.*?^ \})$", extract, body, flags=re.M | re.S)
    heap = " var buffer = new ArrayBuffer(67108864);"
    if len(definitions) != len(PIPE_KERNELS) or body.count(heap) != 1:
        raise SystemExit("The generated pipe kernels or memory layout changed. Review the JavaScript port.")
    kernel_factory = '''function pipeKernels(stdlib, foreign, heap) {
 "use asm";
 var HEAP32 = new stdlib.Int32Array(heap), HEAPF32 = new stdlib.Float32Array(heap);
 var Math_fround = stdlib.Math.fround, Math_imul = stdlib.Math.imul;
 var Math_abs = stdlib.Math.abs, Math_sqrt = stdlib.Math.sqrt;
''' + "\n".join(definitions.values()) + "\n return {renderFlue: renderFlue, renderReed: renderReed};\n}\n"
    return kernel_factory + body.replace(heap, "\n".join([
        heap, " const kernels = pipeKernels(globalThis, {}, buffer);", *bindings,
    ]))


source, destination = map(Path, sys.argv[1:])
body = source.read_text()
wasi_import = "import * as wasi_snapshot_preview1 from 'wasi_snapshot_preview1';"
footer = "\nvar retasmFunc = asmFunc({"
if not body.startswith(wasi_import) or body.count(footer) != 1:
    raise SystemExit("Unexpected wasm2js module format. Use Binaryen 120.")
body = body[len(wasi_import):body.index(footer)]

# Only libc++'s fatal error path refers to diagnostic file descriptors. An
# AudioWorklet has no file descriptors, so surface that failure to its host.
header = """// Generated by scripts/oregana/build-dsp.sh. See LICENSE and RUNTIME-LICENSES.txt.
// Required Notice: Copyright (c) 2026 Protocodus (https://protocodus.cz)
export function createCore() {
  function fileError() { throw new Error("Oregana DSP runtime error"); }
"""
factory = """
  return asmFunc({
    wasi_snapshot_preview1: { fd_close: fileError, fd_write: fileError, fd_seek: fileError }
  });
}
"""
module = header + extract_pipe_kernels(body) + factory
destination.write_text("\n".join(line.rstrip() for line in module.splitlines()) + "\n")
