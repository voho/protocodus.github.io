// Rebuild the shipped v3 river bank after changing the solver. Keep the slot
// count, source seed order and any published v3 physics stable across releases.
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { availableParallelism } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { prepareRiver, restoreRiver, missionFromRiver, roadDeck, memberProblem, V3_RIVERS } from '../js/mission.js';
import { createSim } from '../js/physics.js';

const materials = ['wood', 'steel', 'cable'];

function bake(slot) {
  for (let attempt = 0; attempt < 100; attempt++) {
    const seed = `v2-river${slot.toString(36)}x${attempt.toString(36)}`;
    const data = prepareRiver(seed, 5);
    const river = restoreRiver(data);
    const mission = missionFromRiver(river, 'easy', seed);
    const hard = missionFromRiver(river, 'hard', seed);
    const deck = roadDeck(mission), packed = [];
    let affordable = 0;
    for (const { members, kind, cost } of river.pool) {
      const sim = createSim(mission, members);
      let dry = true;
      while (!sim.result) {
        sim.step();
        if (sim.nodes.some(n => n.y < mission.water + 0.02) || sim.car.axles.some(a => a.y < mission.water + 0.02)) dry = false;
      }
      assert.equal(sim.result, 'win', `${seed}: ${kind} crosses`);
      assert.ok(sim.peakUsage() < 0.95);
      assert.deepEqual(members.slice(0, deck.length), deck);
      if (!dry) {
        if (!packed.length) break;
        continue;
      }
      for (const m of members) assert.equal(memberProblem(mission, [], m), null);
      const supports = members.slice(deck.length).flatMap(m => {
        const material = materials.indexOf(m.mat);
        assert.ok(material >= 0);
        return [...m.a, ...m.b, material];
      });
      packed.push([kind, supports]);
      if (cost <= hard.budget) affordable++;
    }
    if (affordable >= 2 && packed.length >= 3) return [seed, data.tries, packed];
  }
  throw new Error(`Could not prepare slot ${slot}`);
}

if (isMainThread) {
  const workers = Math.min(6, availableParallelism());
  const rows = new Array(V3_RIVERS);
  await Promise.all(Array.from({ length: workers }, (_, first) => new Promise((resolve, reject) => {
    const worker = new Worker(new URL(import.meta.url), { workerData: { first, workers } });
    worker.on('message', ([i, row]) => { rows[i] = row; });
    worker.on('error', reject);
    worker.on('exit', code => code ? reject(new Error(`Worker exited ${code}`)) : resolve());
  })));
  const text = '// Generated by fun/bridger/tools/bake-rivers.mjs. Array order is part of the v3 seed format.\n' +
    'export default [\n' + rows.map(row => JSON.stringify(row)).join(',\n') + '\n];\n';
  await writeFile(new URL('../js/river-catalog.js', import.meta.url), text);
  console.log(`Baked ${rows.length} rivers and ${rows.reduce((n, r) => n + r[2].length, 0)} verified designs.`);
} else {
  for (let i = workerData.first; i < V3_RIVERS; i += workerData.workers) parentPort.postMessage([i, bake(i)]);
}
