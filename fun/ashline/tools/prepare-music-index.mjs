#!/usr/bin/env node
// Index the original MP3 frames for bounded HTTP-range playback and seeking.
// No transcoding or media copies: only this small metadata module is generated.
import {execFileSync} from 'node:child_process';
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const directory = new URL('../assets/audio/', import.meta.url);
const output = new URL('stream-index.js', directory);
const index = {};
for (const file of readdirSync(directory).filter(name => name.endsWith('.mp3')).sort()) {
  const probe = JSON.parse(execFileSync('ffprobe', [
    '-v', 'error', '-show_packets', '-show_format',
    '-show_entries', 'format=duration,size:packet=pts_time,pos',
    '-of', 'json', fileURLToPath(new URL(file, directory)),
  ], {encoding:'utf8', maxBuffer:8 * 1024 * 1024}));
  const points = [[0, 0]];
  let next = 2;
  for (const packet of probe.packets) {
    const time = Number(packet.pts_time), offset = Number(packet.pos);
    if (!Number.isFinite(time) || !Number.isInteger(offset)) throw new Error(`Missing frame position: ${file}`);
    if (time >= next) {
      points.push([time, offset]);
      next = time + 2;
    }
  }
  index[file] = {duration:Number(probe.format.duration), bytes:Number(probe.format.size), points};
}
const source = `// Generated by tools/prepare-music-index.mjs from the original MP3 frames.\n// [seconds, byte offset] points permit seeking without fetching the intervening music.\nexport const MUSIC_INDEX = ${JSON.stringify(index, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw new Error('Music index is stale; run node tools/prepare-music-index.mjs');
  console.log(`Music index verified for ${Object.keys(index).length} original tracks.`);
} else {
  writeFileSync(output, source);
  console.log(`Indexed ${Object.keys(index).length} original tracks without modifying audio.`);
}
