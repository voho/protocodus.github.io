// Bake the authored views at the exact resolution used by the renderer.
// Requires Playwright + Chrome and cwebp (libwebp). No game server is needed.
// ASHLINE_PLAYWRIGHT / ASHLINE_BROWSER / CWEBP override local dependencies.
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'assets/prepared/units');
const temporary = await mkdtemp(join(tmpdir(), 'ashline-unit-atlases-'));
const server = createServer(async (request, response) => {
  try {
    const pathname = new URL(request.url, 'http://localhost').pathname;
    if (pathname === '/') { response.setHeader('Content-Type', 'text/html'); response.end('<!doctype html><title>Unit atlas preparation</title>'); return; }
    // The normalizer is exported by assets.js, but never starts runtime loading.
    // Its generated manifest import must also work before any outputs exist.
    if (pathname === '/assets/prepared/units/manifest.js') { response.setHeader('Content-Type', 'text/javascript'); response.end('export const UNIT_SHEETS = {};'); return; }
    const path = resolve(root, `.${decodeURIComponent(pathname)}`);
    if (!path.startsWith(root.endsWith(sep) ? root : root + sep)) throw new Error('Outside asset directory');
    const data = await readFile(path);
    response.setHeader('Content-Type', path.endsWith('.js') ? 'text/javascript' : path.endsWith('.webp') ? 'image/webp' : 'application/octet-stream');
    response.end(data);
  } catch { response.statusCode = 404; response.end(); }
});
let browser;
try {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const { chromium } = await import(process.env.ASHLINE_PLAYWRIGHT || 'playwright');
  browser = await chromium.launch({ channel: process.env.ASHLINE_BROWSER || 'chrome', headless: true });
  const page = await browser.newPage();
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  const types = await page.evaluate(async () => Object.keys((await import('./sim.js')).UNITS));
  const manifest = {}, sourceBounds = {}, files = new Map();
  let sourceBytes = 0, preparedBytes = 0, sourcePixels = 0, preparedPixels = 0;
  for (const type of types) {
    const result = await page.evaluate(async type => {
      const { prepareUnitAtlas } = await import('./assets.js');
      const image = new Image(); image.src = `./assets/generated/directions/${type}.webp`; await image.decode();
      const { atlas, metadata, sourceBounds } = prepareUnitAtlas(image, type);
      return { png: atlas.toDataURL('image/png').split(',')[1], metadata, sourceBounds,
        sourcePixels: image.width * image.height, preparedPixels: atlas.width * atlas.height };
    }, type);
    const png = join(temporary, `${type}.png`), webp = join(temporary, `${type}.webp`);
    await writeFile(png, Buffer.from(result.png, 'base64'));
    execFileSync(process.env.CWEBP || 'cwebp', ['-quiet', '-lossless', '-exact', '-m', '6', png, '-o', webp]);
    const bytes = await readFile(webp);
    files.set(`${type}.webp`, bytes);
    manifest[type] = result.metadata;
    sourceBounds[type] = Array.from({ length: result.sourceBounds.length / 8 }, (_, pose) => result.sourceBounds.slice(pose * 8, pose * 8 + 8));
    sourceBytes += (await readFile(join(root, `assets/generated/directions/${type}.webp`))).length;
    preparedBytes += bytes.length; sourcePixels += result.sourcePixels; preparedPixels += result.preparedPixels;
    console.log(`${type}: ${result.metadata.pixels * 4}×${result.metadata.pixels * result.metadata.rows}, ${bytes.length.toLocaleString()} bytes`);
  }
  files.set('manifest.js', Buffer.from('// Generated by tools/prepare-unit-atlases.mjs; friendly pixels are already normalized and tinted.\nexport const UNIT_SHEETS = {\n'
    + Object.entries(manifest).map(([type, metadata]) => `  ${JSON.stringify(type)}: ${JSON.stringify(metadata)}`).join(',\n') + '\n};\n'));
  // QA-only extraction records. The game never loads these or the source masters.
  files.set('source-bounds.json', Buffer.from(JSON.stringify(sourceBounds, null, 2) + '\n'));
  if (process.argv.includes('--check')) {
    for (const [name, bytes] of files) assert.deepEqual(await readFile(join(destination, name)), bytes, `${name} is stale; rebuild unit atlases`);
  } else {
    await mkdir(destination, { recursive: true });
    for (const [name, bytes] of files) await writeFile(join(destination, name), bytes);
  }
  console.log(JSON.stringify({ sourceBytes, preparedBytes, sourcePixels, preparedPixels,
    downloadReduction: 1 - preparedBytes / sourceBytes, decodedPixelReduction: 1 - preparedPixels / sourcePixels,
    checked: process.argv.includes('--check') }, null, 2));
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  await rm(temporary, { recursive: true, force: true });
}
