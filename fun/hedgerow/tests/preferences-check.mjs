import './three-hooks.mjs';
import assert from 'node:assert/strict';
import { normalizeSettings } from '../js/settings.js';
import { DEFAULT_SETTINGS } from '../js/config.js';
import { createInput } from '../js/input.js';
const { createCameraRig } = await import('../js/camera.js');
const THREE = await import('three');

for (const bad of [null, [], 42, 'old save']) assert.deepEqual(normalizeSettings(bad), DEFAULT_SETTINGS);
const repaired = normalizeSettings({ fov: 999, volume: -4, sensitivity: NaN, quality: 'constructor', difficulty: '__proto__', cameraShake: 'false', motionBlur: true, ambienceVolume: 0.35, unknown: 4 });
assert.equal(repaired.fov, 90);
assert.equal(repaired.volume, 0);
assert.equal(repaired.sensitivity, DEFAULT_SETTINGS.sensitivity);
assert.equal(repaired.quality, 'high');
assert.equal(repaired.difficulty, 'regular');
assert.equal(repaired.cameraShake, true);
assert.equal(repaired.motionBlur, true);
assert.equal(repaired.ambienceVolume, 0.35);
assert.equal(repaired.unknown, undefined);

const windowEvents = new Map(), documentEvents = new Map(), canvasEvents = new Map();
globalThis.window = { addEventListener: (name, fn) => windowEvents.set(name, fn) };
let exits = 0;
globalThis.document = { addEventListener: (name, fn) => documentEvents.set(name, fn), pointerLockElement: null, exitPointerLock() { exits++; this.pointerLockElement = null; } };
let requests = 0;
const canvas = { addEventListener: (name, fn) => canvasEvents.set(name, fn), requestPointerLock: async () => { requests++; throw new Error('unsupported'); } };
const input = createInput(canvas);
input.enable(true);
document.pointerLockElement = canvas;
documentEvents.get('pointerlockchange')();
windowEvents.get('keydown')({ code: 'KeyW', preventDefault() {} });
windowEvents.get('mousemove')({ movementX: 32, movementY: -14 });
windowEvents.get('wheel')({ deltaY: 1 });
canvasEvents.get('mousedown')({ button: 0 });
assert.ok(input.held('KeyW') && input.fired());
input.enable(false);
input.enable(true);
assert.equal(input.held('KeyW'), false);
assert.equal(input.pressed('KeyW'), false);
assert.equal(input.fired(), false);
assert.deepEqual(input.consumeMouse(), [0, 0]);
assert.equal(input.consumeWheel(), 0);
let unlocks = 0;
input.on('unlock', () => unlocks++);
await input.requestLock();
assert.equal(requests, 2, 'retry without raw mouse input');
assert.equal(unlocks, 1, 'denied pointer lock returns to pause');
input.enable(false);
document.pointerLockElement = canvas;
documentEvents.get('pointerlockchange')();
assert.equal(exits, 1, 'a lock granted after pause is immediately released');
const legacyInput = createInput({ addEventListener() {}, requestPointerLock() {} });
let legacyUnlock = 0;
legacyInput.on('unlock', () => legacyUnlock++);
legacyInput.enable(true);
await legacyInput.requestLock();
documentEvents.get('pointerlockerror')();
assert.equal(legacyUnlock, 1, 'legacy event-only pointer lock denial is handled');

const camera = new THREE.PerspectiveCamera(68, 1.6, 0.05, 1000);
const rig = createCameraRig(camera, {});
rig.cameraMotion = 0;
rig.addShake(1);
rig.flinch(1);
rig.daze = 1;
rig.kick(0.03, 0.01);
const eye = new THREE.Vector3(1, 1.62, 2);
rig.updateFirstPerson(1 / 60, eye, null, false, {moveSpeed: 5, strafe: 3, sprint: true});
assert.ok(camera.position.distanceTo(eye) < 1e-10, 'disabled camera movement removes cosmetic bob/shake');
assert.equal(camera.fov, 68, 'disabled camera movement removes sprint zoom');
assert.ok(camera.getWorldDirection(new THREE.Vector3()).distanceTo(rig.forward()) < 1e-8, 'aim and weapon recoil stay aligned');
console.log('preferences-check: corrupt saves recover; sound/display preferences persist; pause clears input; denied lock is handled; reduced camera movement preserves aim');
