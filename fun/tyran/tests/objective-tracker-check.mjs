import assert from 'node:assert/strict';
import { objectiveTracker } from '../objective-tracker.js';

assert.equal(objectiveTracker(null), null);
assert.equal(objectiveTracker({}), null);
assert.equal(objectiveTracker({ director: { objectives: [{ kind: 'unknown' }] } }), null);
const survivor = { kind: 'survivor', target: 1, done: false };
const squads = { kind: 'squads', target: 3, done: false };
const state = { stats: { squads: 1 }, director: { objectives: [survivor, squads] } };
assert.equal(objectiveTracker(state).label, 'Wipe out 3 squadrons');
assert.equal(objectiveTracker(state).progress, '1 / 3');
state.stats.squads = 3;
assert.equal(objectiveTracker(state).progress, '3 / 3');
assert.equal(objectiveTracker(state).complete, false, 'progress alone never announces a paid objective');
squads.done = true;
assert.equal(objectiveTracker(state).progress, 'On track');
state.stats.lost = 1;
assert.equal(objectiveTracker(state).progress, 'Missed');
survivor.done = true;
assert.equal(objectiveTracker(state).label, 'Objectives complete');
assert.equal(objectiveTracker(state).progress, '2/2');
assert.equal(objectiveTracker(state).complete, true);
const accuracy = { stats: { hits: 9, shots: 20 }, director: { objectives: [{ kind: 'precision', target: 35 }] } };
assert.equal(objectiveTracker(accuracy).label, 'Accuracy at sector clear');
assert.equal(objectiveTracker(accuracy).progress, '45% / 35%');
assert.equal(objectiveTracker(accuracy).complete, false);
accuracy.stats.shots = 0;
assert.equal(objectiveTracker(accuracy).progress, '0% / 35%');
const dives = { stats: { dives: 6 }, director: { objectives: [{ kind: 'dives', target: 4 }] } };
assert.equal(objectiveTracker(dives).progress, '4 / 4');
const before = JSON.stringify(dives);
objectiveTracker(dives);
assert.equal(JSON.stringify(dives), before, 'rendering never mutates mission progress');
console.log('Objective tracker: priority, progress, final goals, completion and immutability checks passed.');
